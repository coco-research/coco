#!/usr/bin/env bash
# `grok/install.sh --uninstall` must remove everything the installer generated (342 SI
# commands, the config.toml MCP block, the hooks file) and nothing the user owns (#267).
# Runs against a temp HOME, with stub binaries so the MCP and hooks steps fire.
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT=$(pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
export HOME="$tmp/home"
G="$HOME/.grok"
mkdir -p "$HOME/.coco/bin" "$G/commands" "$G/hooks"
printf '#!/bin/sh\n' | tee "$HOME/.coco/bin/coco-platform-mcp" > "$HOME/.coco/bin/coco-m0-hook"
chmod +x "$HOME/.coco/bin/coco-platform-mcp" "$HOME/.coco/bin/coco-m0-hook"

# User-owned files that must survive: a hand-written SI-named command, a private config
# with a key line, another hook. --uninstall must not loosen that mode.
printf '# my own command\n' > "$G/commands/SI-mine.md"
printf 'model = "mine"\napi_key = "dummy"\n' > "$G/config.toml"
chmod 600 "$G/config.toml"
printf '{}\n' > "$G/hooks/other.json"

octal_mode() { stat -c %a "$1" 2>/dev/null || stat -f %Lp "$1"; }

bash adapters/grok/install.sh --systems superintelligence >/dev/null
generated=$({ grep -l 'Generated by `build_' "$G"/commands/SI*.md 2>/dev/null || true; } | wc -l | tr -d ' ')
[[ $generated -gt 300 ]] || { echo "FAIL: setup produced only $generated generated SI commands"; exit 1; }
grep -q 'coco:mcp-start' "$G/config.toml" && [[ -f "$G/hooks/coco-m0.json" ]] \
  || { echo "FAIL: setup did not wire the MCP block and hooks"; exit 1; }

bash adapters/grok/install.sh --uninstall >/dev/null

fail=0
bad() { echo "FAIL: $1"; fail=1; }
left=$(grep -l 'Generated by `build_' "$G"/commands/SI*.md 2>/dev/null | wc -l | tr -d ' ' || true)
[[ $left -eq 0 ]] || bad "$left generated SI commands left behind"
[[ -z "$(find "$G" -type l -lname "$ROOT/*")" ]] || bad "symlinks into the clone left behind"
[[ -f "$G/hooks/coco-m0.json" ]] && bad "hooks/coco-m0.json left behind"
grep -q 'coco:' "$G/config.toml" && bad "config.toml still has the coco block"
[[ -f "$G/commands/SI-mine.md" ]] || bad "user's SI-mine.md was deleted"
grep -qx 'model = "mine"' "$G/config.toml" || bad "user's config.toml content was lost"
grep -qx 'api_key = "dummy"' "$G/config.toml" || bad "user's api_key line was lost"
[[ $(octal_mode "$G/config.toml") == 600 ]] || bad "config.toml is $(octal_mode "$G/config.toml") after --uninstall, want 0600"
[[ -f "$G/hooks/other.json" ]] || bad "user's hooks/other.json was deleted"

# A 0644 config.toml that still holds an api_key must be tightened to 0600.
printf 'api_key = "dummy"\n# coco:mcp-start\n# coco:mcp-end\n' > "$G/config.toml"
chmod 644 "$G/config.toml"
bash adapters/grok/install.sh --uninstall >/dev/null
[[ $(octal_mode "$G/config.toml") == 600 ]] || bad "0644 config.toml with api_key is $(octal_mode "$G/config.toml") after --uninstall, want 0600"

# A config.toml that did not exist yet must be created 0600, not the umask default.
fresh="$tmp/fresh"
GROK_HOME="$fresh" bash adapters/grok/install.sh --core-only >/dev/null
[[ -f "$fresh/config.toml" ]] || bad "fresh install did not create config.toml"
[[ $(octal_mode "$fresh/config.toml") == 600 ]] || bad "fresh config.toml is $(octal_mode "$fresh/config.toml"), want 0600"
exit $fail
