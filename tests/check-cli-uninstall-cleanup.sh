#!/usr/bin/env bash
# `coco uninstall` must remove the update-check cache the CLI itself created (#264),
# every adapter home's links into the clone, and marker-carrying files in the folders
# each adapter writes, never a user file (#224).
# Throwaway HOME and clone only. Git here is local `init`; nothing is fetched.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CLI="${COCO_CLI_BIN:-$ROOT/bin/coco.js}"
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
mkdir -p "$T/home/.coco" "$T/clone"
echo '{}' > "$T/home/.coco/.update-check.json"

HOME="$T/home" node "$CLI" uninstall "$T/clone" >/dev/null

[ ! -e "$T/home/.coco/.update-check.json" ] || { echo "FAIL: .update-check.json left behind"; exit 1; }
[ ! -e "$T/home/.coco" ] || { echo "FAIL: empty ~/.coco left behind"; exit 1; }
[ ! -e "$T/clone" ] || { echo "FAIL: clone left behind"; exit 1; }

# A ~/.coco holding other files must survive.
mkdir -p "$T/home/.coco" "$T/clone"
echo '{}' > "$T/home/.coco/.update-check.json"; echo keep > "$T/home/.coco/other"
HOME="$T/home" node "$CLI" uninstall "$T/clone" >/dev/null
[ -f "$T/home/.coco/other" ] || { echo "FAIL: removed unrelated ~/.coco content"; exit 1; }
echo "PASS: uninstall removes the update-check cache"

# #224: hermes, pi-desktop, and zed install into homes the old sweep never walked.
# COCO_CLI_BIN overrides the CLI under test (the old-homes proof uses it). The
# installers run from the temp clone, so every link points at that clone.
unset GIT_DIR GIT_WORK_TREE GIT_COMMON_DIR GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
  GIT_ALTERNATE_OBJECT_DIRECTORIES GIT_NAMESPACE GIT_CEILING_DIRECTORIES \
  GIT_DISCOVERY_ACROSS_FILESYSTEM GIT_CONFIG GIT_CONFIG_GLOBAL GIT_CONFIG_SYSTEM \
  GIT_CONFIG_NOSYSTEM GIT_CONFIG_PARAMETERS GIT_CONFIG_COUNT || true

mkdir -p "$T/clone"
(
  cd "$ROOT" || exit 1
  git ls-files -z --cached --others --exclude-standard |
    while IFS= read -r -d '' f; do
      if [ -e "$f" ] || [ -L "$f" ]; then printf '%s\0' "$f"; fi
    done |
    tar --null -T - -cf -
) | tar -xf - -C "$T/clone"
git -C "$T/clone" init -q
git -C "$T/clone" add -A
git -C "$T/clone" -c user.email=t@t -c user.name=t commit -qm base
git -C "$T/clone" remote add origin https://github.com/coco-research/coco.git
git -C "$T/clone" update-ref refs/remotes/origin/main HEAD

install_adapter() {
  if ! HOME="$T/home" bash "$T/clone/install.sh" --adapter "$1" >"$T/$1.log" 2>&1; then
    echo "FAIL: $1 install"
    tail -n 40 "$T/$1.log"
    exit 1
  fi
}
install_adapter hermes
install_adapter pi-desktop
install_adapter zed

# User files: one in each home, one inside each folder an adapter writes, two
# notes that quote the PI-Desktop marker text, and an SI-named file without the
# generator line. None of them may be removed.
H="$T/home"
SI_DIR="$H/.hermes/profiles/dev/home/.claude/commands"
mkdir -p "$H/.agents/skills/my-skill" "$H/.claude/projects/demo/memory" "$H/.coco/knowledge"
USER_FILES=(
  "$H/.hermes/user-keep.txt" "$H/.pi/user-keep.txt" "$H/.agents/user-keep.txt"
  "$H/.config/zed/user-keep.txt" "$H/.agents/skills/my-skill/SKILL.md"
  "$H/.agents/subagents/mine.md" "$H/.pi/agent/prompts/mine.md"
  "$H/.config/zed/rules/mine.md" "$SI_DIR/SI-mine.md"
  "$H/.claude/projects/demo/memory/note.md" "$H/.coco/knowledge/note.md"
)
for f in "${USER_FILES[@]}"; do
  [ -d "$(dirname "$f")" ] || { echo "FAIL: installer did not create $(dirname "$f")"; exit 1; }
  echo "user file. Coco PI-Desktop adapter notes." > "$f"
done

[ -n "$(find "$H/.agents/skills" -name SKILL.md -exec grep -l -F '<!-- Coco PI-Desktop adapter. Source: ' {} +)" ] \
  || { echo "FAIL: pi-desktop wrote no marked skills"; exit 1; }
ls "$SI_DIR"/SI-*.md >/dev/null || { echo "FAIL: hermes generated no SI commands"; exit 1; }

CLONE_LOGICAL=$(cd "$T/clone" && pwd)
CLONE_PHYS=$(cd "$T/clone" && pwd -P)

if ! HOME="$H" COCO_NO_UPDATE_CHECK=1 node "$CLI" uninstall "$T/clone" >"$T/out" 2>"$T/err"; then
  echo "FAIL: uninstall of installed clone exited non-zero"
  cat "$T/err"
  exit 1
fi

[ ! -e "$T/clone" ] || { echo "FAIL: installed clone left behind"; exit 1; }

while IFS= read -r -d '' link; do
  target=$(readlink "$link") || { echo "FAIL: unreadable link $link"; exit 1; }
  case "$target" in
    "$CLONE_LOGICAL"|"$CLONE_LOGICAL"/*|"$CLONE_PHYS"|"$CLONE_PHYS"/*)
      echo "FAIL: symlink into clone left: $link -> $target"
      exit 1
      ;;
  esac
done < <(find "$H" -type l -print0)

is_user_file() {
  local u
  for u in "${USER_FILES[@]}"; do [ "$1" = "$u" ] && return 0; done
  return 1
}
while IFS= read -r -d '' f; do
  is_user_file "$f" && continue
  case "$(basename "$f")" in
    SI.md|SI-*.md)
      if grep -q -e 'Generated by `build_commands.py`' -e 'Generated by `build_meta_commands.py`' -- "$f"; then
        echo "FAIL: generated SI file left: $f"
        exit 1
      fi
      ;;
  esac
  if grep -q -F '<!-- Coco PI-Desktop adapter. Source: ' -- "$f"; then
    echo "FAIL: PI-Desktop marker file left: $f"
    exit 1
  fi
done < <(find "$H" -type f -print0)

for f in "${USER_FILES[@]}"; do
  grep -q '^user file' "$f" 2>/dev/null || { echo "FAIL: user file removed: $f"; exit 1; }
done

notes=$(grep '^Note: .* install was not fully removed\.$' "$T/out" | sort || true)
expected=$(printf '%s\n' \
  'Note: hermes install was not fully removed.' \
  'Note: zed install was not fully removed.' | sort)
[ "$notes" = "$expected" ] || { echo "FAIL: leftover notes:"; printf '%s\n' "$notes"; echo "--- out ---"; cat "$T/out"; exit 1; }
echo "PASS: uninstall cleans hermes, pi-desktop, and zed links and marker files, and keeps user files"
