#!/usr/bin/env bash
# `grok/install.sh --uninstall` must remove everything the installer generated (342 SI
# commands, the config.toml MCP block, the hooks file) and nothing the user owns (#267).
# Runs against a temp HOME, with stub binaries so the MCP and hooks steps fire.
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT=$(pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
export HOME="$tmp/home"
G="$HOME/.grok"
mkdir -p "$HOME/.coco/bin" "$G/commands" "$G/hooks"
printf '#!/bin/sh\n' | tee "$HOME/.coco/bin/coco-platform-mcp" > "$HOME/.coco/bin/coco-m0-hook"
chmod +x "$HOME/.coco/bin/coco-platform-mcp" "$HOME/.coco/bin/coco-m0-hook"

# User-owned files that must survive: a hand-written SI-named command, a private config
# with a key line, another hook. --uninstall must not loosen that mode.
printf '# my own command\n' > "$G/commands/SI-mine.md"
printf 'model = "mine"\napi_key = "dummy"\n' > "$G/config.toml"
chmod 600 "$G/config.toml"
printf '{}\n' > "$G/hooks/other.json"

octal_mode() { stat -c %a "$1" 2>/dev/null || stat -f %Lp "$1"; }

bash adapters/grok/install.sh --systems superintelligence >/dev/null
generated=$({ grep -l 'Generated by `build_' "$G"/commands/SI*.md 2>/dev/null || true; } | wc -l | tr -d ' ')
[[ $generated -gt 300 ]] || { echo "FAIL: setup produced only $generated generated SI commands"; exit 1; }
grep -q 'coco:mcp-start' "$G/config.toml" && [[ -f "$G/hooks/coco-m0.json" ]] \
  || { echo "FAIL: setup did not wire the MCP block and hooks"; exit 1; }

bash adapters/grok/install.sh --uninstall >/dev/null

fail=0
bad() { echo "FAIL: $1"; fail=1; }
left=$(grep -l 'Generated by `build_' "$G"/commands/SI*.md 2>/dev/null | wc -l | tr -d ' ' || true)
[[ $left -eq 0 ]] || bad "$left generated SI commands left behind"
[[ -z "$(find "$G" -type l -lname "$ROOT/*")" ]] || bad "symlinks into the clone left behind"
[[ -f "$G/hooks/coco-m0.json" ]] && bad "hooks/coco-m0.json left behind"
grep -q 'coco:' "$G/config.toml" && bad "config.toml still has the coco block"
[[ -f "$G/commands/SI-mine.md" ]] || bad "user's SI-mine.md was deleted"
grep -qx 'model = "mine"' "$G/config.toml" || bad "user's config.toml content was lost"
grep -qx 'api_key = "dummy"' "$G/config.toml" || bad "user's api_key line was lost"
[[ $(octal_mode "$G/config.toml") == 600 ]] || bad "config.toml is $(octal_mode "$G/config.toml") after --uninstall, want 0600"
[[ -f "$G/hooks/other.json" ]] || bad "user's hooks/other.json was deleted"

# A 0644 config.toml that still holds an api_key must be tightened to 0600.
printf 'api_key = "dummy"\n# coco:mcp-start\n# coco:mcp-end\n' > "$G/config.toml"
chmod 644 "$G/config.toml"
bash adapters/grok/install.sh --uninstall >/dev/null
[[ $(octal_mode "$G/config.toml") == 600 ]] || bad "0644 config.toml with api_key is $(octal_mode "$G/config.toml") after --uninstall, want 0600"

# A config.toml that did not exist yet must be created 0600, not the umask default.
fresh="$tmp/fresh"
GROK_HOME="$fresh" bash adapters/grok/install.sh --core-only >/dev/null
[[ -f "$fresh/config.toml" ]] || bad "fresh install did not create config.toml"
[[ $(octal_mode "$fresh/config.toml") == 600 ]] || bad "fresh config.toml is $(octal_mode "$fresh/config.toml"), want 0600"

# A symlinked config.toml (0600, no secret) stays a link; the target keeps its mode.
rm -f "$G/config.toml"
linked_cfg="$tmp/dotfiles-config.toml"
printf 'model = "linked"\n# coco:mcp-start\ncommand = "x"\n# coco:mcp-end\n' > "$linked_cfg"
chmod 600 "$linked_cfg"
ln -s "$linked_cfg" "$G/config.toml"
saved_umask=$(umask)
umask 022
bash adapters/grok/install.sh --uninstall >/dev/null
umask "$saved_umask"
[[ -L "$G/config.toml" ]] || bad "symlinked config.toml was replaced"
[[ "$(readlink "$G/config.toml")" == "$linked_cfg" ]] || bad "config symlink no longer points at its target"
grep -q 'coco:' "$linked_cfg" && bad "symlink target still has the coco:mcp block"
[[ $(octal_mode "$linked_cfg") == 600 ]] || bad "symlink target mode is $(octal_mode "$linked_cfg"), want 0600 (never 0777)"

# A symlinked config whose only content is the coco:mcp block stays: the empty
# target file remains, and the link still points at it.
rm -f "$G/config.toml"
only_block="$tmp/only-block-config.toml"
printf '# coco:mcp-start\n# coco:mcp-end\n' > "$only_block"
ln -s "$only_block" "$G/config.toml"
empty_note=$(bash adapters/grok/install.sh --uninstall 2>&1)
[[ -f "$only_block" ]] || bad "symlinked config target was deleted"
[[ ! -s "$only_block" ]] || bad "symlinked config target was not left empty"
[[ -L "$G/config.toml" ]] || bad "config symlink was removed"
[[ "$(readlink "$G/config.toml")" == "$only_block" ]] || bad "config symlink no longer points at the emptied target"
[[ "$empty_note" == *"left the empty target in place"* ]] || bad "empty symlink target did not print a note: $empty_note"

# A regular config.toml holding only the coco:mcp block is removed.
reg_only="$tmp/regular-only-block"
mkdir -p "$reg_only"
printf '# coco:mcp-start\n# coco:mcp-end\n' > "$reg_only/config.toml"
GROK_HOME="$reg_only" bash adapters/grok/install.sh --uninstall >/dev/null
[[ -e "$reg_only/config.toml" || -L "$reg_only/config.toml" ]] && bad "regular config.toml holding only the coco:mcp block still exists"

# Symlinked config must uninstall with no realpath and a readlink that rejects -f.
rm -f "$G/config.toml"
port_cfg="$tmp/portable-config.toml"
printf 'model = "portable"\n# coco:mcp-start\ncommand = "x"\n# coco:mcp-end\n' > "$port_cfg"
ln -s "../../portable-config.toml" "$G/config.toml"
portable_shim="$tmp/portable-shim"
mkdir -p "$portable_shim"
real_readlink=$(PATH="/usr/bin:/bin" command -v readlink)
cat > "$portable_shim/readlink" << EOF
#!/bin/sh
if [ "\${1-}" = "-f" ]; then
  echo "readlink: illegal option -- f" >&2
  exit 1
fi
exec $real_readlink "\$@"
EOF
chmod +x "$portable_shim/readlink"
for c in find grep mktemp stat chmod mv rm rmdir awk dirname; do
  ln -s "$(PATH="/usr/bin:/bin" command -v "$c")" "$portable_shim/$c"
done
PATH="$portable_shim" command -v realpath >/dev/null 2>&1 && bad "fixture PATH still has realpath"
PATH="$portable_shim" readlink -f "$port_cfg" >/dev/null 2>&1 && bad "fixture readlink -f should fail"
port_status=0
# Prefixing PATH changes bash's command lookup, so invoke bash by absolute path.
PATH="$portable_shim" "$(command -v bash)" adapters/grok/install.sh --uninstall >/dev/null || port_status=$?
[[ $port_status -eq 0 ]] || bad "portable readlink: uninstall exited $port_status"
[[ "$(readlink "$G/config.toml")" == "../../portable-config.toml" ]] || bad "portable readlink: config symlink was rewritten"
grep -q 'coco:' "$port_cfg" && bad "portable readlink: symlink target still has the coco block"
grep -qx 'model = "portable"' "$port_cfg" || bad "portable readlink: user content lost"

# A dangling config symlink refuses before the clone sweep or command removal.
dang="$tmp/dangling-home"
mkdir -p "$dang/commands" "$dang/skills"
printf 'Generated by `build_commands.py`\n' > "$dang/commands/SI-keep.md"
ln -s "$ROOT/AGENTS.md" "$dang/skills/from-clone"
ln -s "$tmp/missing-config.toml" "$dang/config.toml"
dang_status=0
dang_out=$(GROK_HOME="$dang" bash adapters/grok/install.sh --uninstall 2>&1) || dang_status=$?
[[ $dang_status -ne 0 ]] || bad "dangling config symlink: uninstall exited 0"
[[ "$dang_out" == *"symlink does not resolve to a regular file"* ]] || bad "dangling config symlink did not refuse: $dang_out"
[[ "$dang_out" != *"Removed Coco-generated files"* ]] || bad "dangling config symlink still reported removal: $dang_out"
[[ -f "$dang/commands/SI-keep.md" ]] || bad "dangling config symlink: generated SI command was removed"
[[ -L "$dang/skills/from-clone" ]] || bad "dangling config symlink: clone symlink was removed"
[[ -L "$dang/config.toml" ]] || bad "dangling config symlink was removed"

# A self-referential config.toml must refuse before any removal, and must not hang.
cyc="$tmp/cycle-home"
mkdir -p "$cyc/commands" "$cyc/skills"
printf 'Generated by `build_commands.py`\n' > "$cyc/commands/SI-keep.md"
ln -s "$ROOT/AGENTS.md" "$cyc/skills/from-clone"
ln -s config.toml "$cyc/config.toml"
cyc_status=0
cyc_out_file="$tmp/cycle-out"
if command -v timeout >/dev/null 2>&1; then
  cyc_out=$(GROK_HOME="$cyc" timeout 10 bash adapters/grok/install.sh --uninstall 2>&1) || cyc_status=$?
else
  GROK_HOME="$cyc" bash adapters/grok/install.sh --uninstall >"$cyc_out_file" 2>&1 &
  cyc_pid=$!
  (
    sleep 10
    kill "$cyc_pid" 2>/dev/null || true
  ) &
  cyc_killer=$!
  wait "$cyc_pid" || cyc_status=$?
  kill "$cyc_killer" 2>/dev/null || true
  wait "$cyc_killer" 2>/dev/null || true
  cyc_out=$(cat "$cyc_out_file" 2>/dev/null || true)
fi
[[ $cyc_status -ne 0 ]] || bad "self-referential config symlink: uninstall exited 0"
[[ $cyc_status -ne 124 && $cyc_status -ne 137 && $cyc_status -ne 143 ]] || bad "self-referential config symlink: uninstall hung"
[[ "$cyc_out" == *"exceeded 40 hops"* ]] || bad "self-referential config symlink did not refuse: $cyc_out"
[[ "$cyc_out" != *"Removed Coco-generated files"* ]] || bad "self-referential config symlink still reported removal: $cyc_out"
[[ -f "$cyc/commands/SI-keep.md" ]] || bad "self-referential config symlink: generated SI command was removed"
[[ -L "$cyc/skills/from-clone" ]] || bad "self-referential config symlink: clone symlink was removed"
[[ -L "$cyc/config.toml" ]] || bad "self-referential config symlink was removed"

# GROK_HOME=/ must refuse before any removal is planned.
root_status=0
root_out=$(GROK_HOME=/ bash adapters/grok/install.sh --uninstall --dry-run 2>&1) || root_status=$?
[[ $root_status -ne 0 ]] || bad "GROK_HOME=/ --uninstall --dry-run exited 0"
[[ "$root_out" == *"Refusing to uninstall"* ]] || bad "GROK_HOME=/ --uninstall --dry-run did not refuse: $root_out"
[[ "$root_out" != *"DRY:"* ]] || bad "GROK_HOME=/ --uninstall --dry-run planned removals: $root_out"

# //, /./, and a symlink to / are the root once canonicalized.
rootlink="$tmp/symlink-to-root"
ln -s / "$rootlink"
for home in '//' '/./' "$rootlink"; do
  st=0
  out=$(GROK_HOME="$home" bash adapters/grok/install.sh --uninstall --dry-run 2>&1) || st=$?
  [[ $st -ne 0 ]] || bad "GROK_HOME=$home --uninstall --dry-run exited 0"
  [[ "$out" == *"Refusing to uninstall"* ]] || bad "GROK_HOME=$home --uninstall --dry-run did not refuse: $out"
  [[ "$out" != *"DRY:"* ]] || bad "GROK_HOME=$home --uninstall --dry-run planned removals: $out"
done

# A symlinked ~/.grok still has clone symlinks inside the target removed.
realgrok="$tmp/real-grok"
linkhome="$tmp/link-home"
mkdir -p "$realgrok/skills" "$linkhome"
ln -s "$realgrok" "$linkhome/.grok"
ln -s "$ROOT/AGENTS.md" "$realgrok/skills/from-clone"
printf 'keep\n' > "$realgrok/skills/mine.txt"
GROK_HOME="$linkhome/.grok" bash adapters/grok/install.sh --uninstall >/dev/null
[[ -L "$realgrok/skills/from-clone" ]] && bad "clone symlink inside symlinked ~/.grok was not removed"
[[ -f "$realgrok/skills/mine.txt" ]] || bad "user file inside symlinked ~/.grok was removed"
[[ -L "$linkhome/.grok" ]] || bad "symlinked ~/.grok itself was removed"

# An exported CDPATH must not redirect a relative GROK_HOME onto a decoy of the same name.
cdpath_real_parent="$tmp/cdpath-work"
cdpath_decoy_parent="$tmp/cdpath-decoy"
mkdir -p "$cdpath_real_parent/relgrok/commands" "$cdpath_decoy_parent/relgrok/commands"
printf 'Generated by `build_commands.py`\n' > "$cdpath_real_parent/relgrok/commands/SI-real.md"
printf 'Generated by `build_commands.py`\n' > "$cdpath_decoy_parent/relgrok/commands/SI-decoy.md"
(
  cd "$cdpath_real_parent"
  CDPATH="$cdpath_decoy_parent" GROK_HOME=relgrok bash "$ROOT/adapters/grok/install.sh" --uninstall >/dev/null
)
[[ -f "$cdpath_decoy_parent/relgrok/commands/SI-decoy.md" ]] || bad "CDPATH decoy SI file was removed"
[[ -e "$cdpath_real_parent/relgrok/commands/SI-real.md" ]] && bad "CDPATH: real target SI file was not removed"

# commands/ symlinked to a directory outside the target must not be swept.
outside_cmds="$tmp/outside-commands"
cmdlink_home="$tmp/cmdlink-home"
mkdir -p "$outside_cmds" "$cmdlink_home"
printf 'Generated by `build_commands.py`\n' > "$outside_cmds/SI-x.md"
ln -s "$outside_cmds" "$cmdlink_home/commands"
cmdlink_out=$(GROK_HOME="$cmdlink_home" bash adapters/grok/install.sh --uninstall 2>&1)
[[ -f "$outside_cmds/SI-x.md" ]] || bad "commands symlink: outside SI-x.md was removed"
[[ "$cmdlink_out" == *"skipped the command sweep"* ]] || bad "commands symlink: no skip note: $cmdlink_out"

# A generated SI file whose name contains a newline is removed; uninstall exits 0.
nlfile="$G/commands/$(printf 'SI-a\nb.md')"
printf 'Generated by `build_commands.py`\n' > "$nlfile"
nl_status=0
bash adapters/grok/install.sh --uninstall >/dev/null || nl_status=$?
[[ $nl_status -eq 0 ]] || bad "newline filename: uninstall exited $nl_status"
[[ -e "$nlfile" ]] && bad "generated SI file with a newline in its name was not removed"
exit $fail
