#!/usr/bin/env bash
# Cursor uninstall must delete generated SI-* commands and keep a user file
# that uses the same name shape but not the generator marker (#208).
set -euo pipefail
cd "$(dirname "$0")/.."

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
export HOME="$tmp"
# The installer prefers CURSOR_HOME over HOME; a caller's value would point it at a real tree.
unset CURSOR_HOME

bash adapters/cursor/install.sh >/dev/null

manifest="$tmp/generated.txt"
find "$HOME/.cursor/commands" -maxdepth 1 -type f -name 'SI-*.md' | sort > "$manifest"
count=$(wc -l < "$manifest" | tr -d ' ')
[[ "$count" -gt 0 ]] || { echo "FAIL: no SI-* command files after install"; exit 1; }

while IFS= read -r f; do
  grep -q -e 'Generated by `build_commands.py`' -e 'Generated by `build_meta_commands.py`' -- "$f" \
    || { echo "FAIL: generated file lacks the generator marker: $f"; exit 1; }
done < "$manifest"

printf '# my own command\n' > "$HOME/.cursor/commands/SI-mine.md"

bash adapters/cursor/install.sh --uninstall >/dev/null

while IFS= read -r f; do
  [[ -e "$f" ]] && { echo "FAIL: generated file still present: $f"; exit 1; }
done < "$manifest"

[[ -f "$HOME/.cursor/commands/SI-mine.md" ]] || { echo "FAIL: SI-mine.md was removed"; exit 1; }
grep -qx '# my own command' "$HOME/.cursor/commands/SI-mine.md" \
  || { echo "FAIL: SI-mine.md contents changed"; exit 1; }

left=$(find "$HOME/.cursor/commands" -maxdepth 1 -type f \( -name 'SI.md' -o -name 'SI-*.md' \) ! -name 'SI-mine.md' | wc -l | tr -d ' ')
[[ "$left" -eq 0 ]] || { echo "FAIL: $left generated SI command(s) left behind"; exit 1; }

echo "PASS: generated SI-* commands removed; SI-mine.md kept"
