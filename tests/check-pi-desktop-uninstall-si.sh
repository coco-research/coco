#!/usr/bin/env bash
# `pi-desktop/install.sh --uninstall` must remove the generated SI prompts (SI.md, SI-*.md),
# which carry the generator's marker rather than the adapter's, and nothing the user owns (#226).
# Runs against a temp HOME; no network.
set -euo pipefail
cd "$(dirname "$0")/.."
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
export HOME="$tmp/home"
# The adapter honours these over HOME; a developer's real values would point the
# install and the uninstall at their real PI folders.
unset PI_AGENT_HOME AGENTS_HOME
mkdir -p "$HOME"
P="$HOME/.pi/agent/prompts"
GEN1='Generated by `build_commands.py`'
GEN2='Generated by `build_meta_commands.py`'
ADAPTER_MARKER='Coco PI-Desktop adapter'

fail=0
bad() { echo "FAIL: $1"; fail=1; }
# Regular files only: -type f skips symlinks, so a user's link is never counted as ours.
# grep exits 1 on no match, which pipefail would turn into a set -e exit.
count_marked() { { find "${@:2}" -type f -exec grep -lF -e "$1" -- {} + 2>/dev/null || true; } | wc -l | tr -d ' '; }

bash install.sh --adapter pi-desktop >/dev/null 2>&1
[[ -f "$P/SI.md" ]] || { echo "FAIL: setup did not generate SI.md"; exit 1; }
generated=$(count_marked "$GEN1" "$P")
[[ $generated -gt 0 ]] || { echo "FAIL: setup generated no SI-* prompts"; exit 1; }

# A user's own SI-named prompt, and a symlink to a generator-marked file outside the folder.
printf '# my own SI prompt\n' > "$P/SI-mine.md"
cp "$P/SI-mine.md" "$tmp/SI-mine.orig"
printf '%s\n' "$GEN1" > "$tmp/outside.md"
ln -s "$tmp/outside.md" "$P/SI-link.md"

dry=$(bash adapters/pi-desktop/install.sh --uninstall --dry-run)
[[ -f "$P/SI.md" ]] || bad "--dry-run removed SI.md"
[[ "$dry" == *"DRY: remove $P/SI.md"* ]] || bad "--dry-run did not list SI.md"
[[ "$dry" != *"Would remove: 0 entries"* ]] || bad "--dry-run reported 0 entries"

bash adapters/pi-desktop/install.sh --uninstall >/dev/null

left=$(( $(count_marked "$GEN1" "$P") + $(count_marked "$GEN2" "$P") ))
[[ $left -eq 0 ]] || bad "$left generated SI prompts left behind"
[[ -f "$P/SI-mine.md" ]] && cmp -s "$P/SI-mine.md" "$tmp/SI-mine.orig" || bad "user's SI-mine.md changed or was deleted"
[[ -L "$P/SI-link.md" && -f "$tmp/outside.md" ]] || bad "symlinked SI-link.md or its target was removed"
[[ $(count_marked "$ADAPTER_MARKER" "$HOME/.pi" "$HOME/.agents") -eq 0 ]] || bad "adapter-marked files left behind"
extra=$(find "$P" -mindepth 1 ! -name SI-mine.md ! -name SI-link.md | wc -l | tr -d ' ')
[[ $extra -eq 0 ]] || bad "$extra other entries left in the prompts folder"

bash adapters/pi-desktop/install.sh --uninstall >/dev/null || bad "second --uninstall did not exit 0"

[[ $fail -eq 0 ]] && echo "PASS: pi-desktop --uninstall removes the generated SI prompts"
exit $fail
